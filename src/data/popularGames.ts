export const getSteamIconUrl = (steamAppId: number): string =>
  `https://cdn.cloudflare.steamstatic.com/steam/apps/${steamAppId}/header.jpg`;

export const searchGames = (query: string): KnownGame[] => {
  if (!query.trim()) return [];
  const q = query.toLowerCase();
  return POPULAR_GAMES.filter((g) => g.name.toLowerCase().includes(q)).slice(0, 8);
};
